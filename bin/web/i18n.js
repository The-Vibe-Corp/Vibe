  var LOCALES = {en: 'en-US', de: 'de-DE'};
  var STORAGE_KEY = 'vibe_i18n_lang';
  var DEFAULT_LANG = 'en';

  function isSupported(value) {
    return typeof value === 'string'
      && Object.prototype.hasOwnProperty.call(DICTS, value);
  }

  function readStored() {
    try {
      var store = global.localStorage || (typeof localStorage !== 'undefined' ? localStorage : null);
      var value = store && store.getItem(STORAGE_KEY);
      return isSupported(value) ? value : null;
    } catch (error) { return null; }
  }

  /* AP21 v2: Der Server rendert die globale Sprache in
     <meta name="vibe-language" content="…">. Dieses Meta-Feld hat Vorrang vor
     localStorage, damit die Wahl in jedem Browser-Kontext gilt. Die Validierung
     ist bewusst vollstaendig: nur exakte, unterstuetzte Codes werden
     uebernommen; ein defektes oder fremdes Meta-Feld faellt auf den
     localStorage-Wert bzw. 'en' zurueck. */
  function readMeta() {
    try {
      var doc = global.document;
      if (!doc || typeof doc.querySelector !== 'function') return null;
      var node = doc.querySelector('meta[name="vibe-language"]');
      var value = node && (node.getAttribute
        ? node.getAttribute('content') : node.content);
      return isSupported(value) ? value : null;
    } catch (error) { return null; }
  }

  var lang = readMeta() || readStored() || DEFAULT_LANG;

  function available() { return Object.keys(DICTS); }
  function current() { return lang; }
  function locale() { return LOCALES[lang] || LOCALES[DEFAULT_LANG]; }

  function t(key, vars) {
    var text = key;
    var dict = DICTS[lang] || DICTS[DEFAULT_LANG];
    if (Object.prototype.hasOwnProperty.call(dict, key)) text = dict[key];
    else if (Object.prototype.hasOwnProperty.call(DICTS[DEFAULT_LANG], key)) text = DICTS[DEFAULT_LANG][key];
    text = String(text);
    if (vars) {
      Object.keys(vars).forEach(function (name) {
        text = text.split('{{' + name + '}}').join(String(vars[name]));
      });
    }
    return text;
  }

  function applyLang(value) {
    var doc = global.document;
    if (doc && doc.documentElement) {
      doc.documentElement.setAttribute('lang', value);
      try { doc.documentElement.lang = value; } catch (error) { /* attrs suffice */ }
    }
  }

  function set(next) {
    if (!Object.prototype.hasOwnProperty.call(DICTS, next)) return false;
    lang = next;
    applyLang(lang);
    try {
      var store = global.localStorage || (typeof localStorage !== 'undefined' ? localStorage : null);
      if (store) store.setItem(STORAGE_KEY, lang);
    } catch (error) { /* private mode: session-only choice */ }
    try {
      global.dispatchEvent(new global.CustomEvent('vibe:langchange', {detail: {lang: lang}}));
    } catch (error) { /* older browsers: listeners poll current() */ }
    return true;
  }

  function formatNumber(value) { return Number(value || 0).toLocaleString(locale()); }
  function formatCurrency(value) {
    return Number(value || 0).toLocaleString(locale(), {minimumFractionDigits: 4, maximumFractionDigits: 4}) + ' €';
  }

  var api = {
    available: available,
    current: current,
    set: set,
    t: t,
    locale: locale,
    formatNumber: formatNumber,
    formatCurrency: formatCurrency,
    number: formatNumber,
    currency: formatCurrency,
    DICTS: DICTS
  };
  global.VIBE_I18N = api;
  global.I18N = api;
  applyLang(lang);
